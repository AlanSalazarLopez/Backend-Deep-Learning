CREATE TABLE IF NOT EXISTS users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,                 -- solo hash Argon2id
  name          TEXT NOT NULL,
  role          TEXT NOT NULL DEFAULT 'client', -- 'client' | 'admin' (lo valida Pydantic)
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS niches (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug           TEXT NOT NULL UNIQUE,
  name           TEXT NOT NULL,
  yt_category_id INTEGER NOT NULL UNIQUE       -- categoryId que YouTube trae en cada video
);

CREATE TABLE IF NOT EXISTS channels (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       INTEGER UNIQUE REFERENCES users(id) ON DELETE CASCADE, -- NULL = canal semilla; un cliente = un canal
  yt_channel_id TEXT NOT NULL UNIQUE,
  handle        TEXT NOT NULL,                 -- con @, ej. '@micanal'
  title         TEXT NOT NULL,
  niche_id      INTEGER REFERENCES niches(id), -- NULL hasta que el cliente confirma su nicho
  source        TEXT NOT NULL DEFAULT 'client', -- 'client' | 'seed'
  language      TEXT,                          -- idioma mayoritario de sus titulos ('es', 'en'...); lo calcula la ingesta. El modelo entrena solo con 'es'
  fetched_at    TIMESTAMPTZ
  -- Si un cliente registra un canal que ya existe como semilla: UPDATE user_id y source='client'.
  -- Si el canal ya pertenece a OTRO usuario: error 409.
);

CREATE TABLE IF NOT EXISTS videos (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  channel_id     INTEGER NOT NULL REFERENCES channels(id) ON DELETE CASCADE,
  yt_video_id    TEXT NOT NULL UNIQUE,
  title          TEXT NOT NULL,
  published_at   TIMESTAMPTZ NOT NULL,
  duration_s     INTEGER NOT NULL,
  views          BIGINT NOT NULL,
  likes          BIGINT,
  comments       BIGINT,
  yt_category_id INTEGER,
  is_short       BOOLEAN NOT NULL DEFAULT FALSE, -- duration_s <= 60, calculado al ingestar
  fetched_at     TIMESTAMPTZ NOT NULL           -- cuando se leyeron las vistas; la EDAD se mide contra esta fecha, no contra now()
);

CREATE TABLE IF NOT EXISTS model_runs (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trained_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  trained_by  INTEGER REFERENCES users(id) ON DELETE SET NULL,
  config      JSONB NOT NULL,                  -- ver docs/C3_ml.md, seccion 2
  metrics     JSONB NOT NULL,                  -- ver docs/C3_ml.md, seccion 5
  n_videos    INTEGER NOT NULL,
  n_channels  INTEGER NOT NULL,
  artifact    BYTEA NOT NULL,                  -- modelo serializado EN la BD: el disco de Render gratis es efimero
  is_active   BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX IF NOT EXISTS one_active_model ON model_runs (is_active) WHERE is_active;

CREATE TABLE IF NOT EXISTS predictions (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  niche_id        INTEGER NOT NULL REFERENCES niches(id),
  model_run_id    INTEGER REFERENCES model_runs(id) ON DELETE SET NULL,
  title           TEXT NOT NULL,
  duration_s      INTEGER NOT NULL,
  publish_hour    INTEGER NOT NULL,
  publish_weekday INTEGER NOT NULL,            -- 0 = lunes ... 6 = domingo
  probability     REAL NOT NULL,               -- 0..1
  score           REAL NOT NULL,               -- 0..100, percentil dentro del nicho
  top_terms       JSONB NOT NULL DEFAULT '[]'::jsonb, -- [{"term": "...", "weight": 0.5}]
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_videos_channel    ON videos(channel_id);
CREATE INDEX IF NOT EXISTS idx_videos_published  ON videos(published_at);
CREATE INDEX IF NOT EXISTS idx_channels_niche    ON channels(niche_id);
CREATE INDEX IF NOT EXISTS idx_predictions_user  ON predictions(user_id, created_at DESC);

