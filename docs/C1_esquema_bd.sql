-- Canales que el descubrimiento encontró y todavía no son canales de la BD (o que se rechazaron).
-- status: 'new' (en la banca, compite cada semana por un lugar) | 'ingested' | 'rejected' (con motivo).
-- Guardar también los rechazados evita volver a gastar cuota en ellos la semana siguiente.
CREATE TABLE IF NOT EXISTS channel_candidates (
  yt_channel_id   TEXT PRIMARY KEY,
  handle          TEXT NOT NULL DEFAULT '',
  title           TEXT NOT NULL DEFAULT '',
  niche_id        INTEGER NOT NULL REFERENCES niches(id),
  country         TEXT,
  subscribers     BIGINT NOT NULL DEFAULT 0,
  video_count     INTEGER NOT NULL DEFAULT 0,
  channel_created TIMESTAMPTZ,
  in_popular      BOOLEAN NOT NULL DEFAULT FALSE,   -- apareció en la lista "más populares" de YouTube
  hits            INTEGER NOT NULL DEFAULT 1,       -- en cuántas búsquedas/listas ha salido (acumulado por semana)
  score           REAL,                             -- puntaje de preselección (se recalcula en cada corrida)
  pool            TEXT,                             -- 'established' | 'prospect'
  status          TEXT NOT NULL DEFAULT 'new',
  reject_reason   TEXT,
  first_seen      TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_seen       TIMESTAMPTZ NOT NULL DEFAULT now(),
  decided_at      TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_candidates_status ON channel_candidates(status, niche_id);

-- Unidades de cuota gastadas por paso en cada corrida (para no pasarse de las 10,000 diarias).
CREATE TABLE IF NOT EXISTS quota_log (
  id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ran_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  step   TEXT NOT NULL,
  units  INTEGER NOT NULL
);


